# Experiment 2: Baseline vs Enhanced Prompt Engineering

# Install the library without upgrading Colab dependencies
# %pip -q install google-genai

from google import genai
from getpass import getpass

try:
    # Step 1: Enter API key securely
    api_key = getpass("Enter your Gemini API key: ")

    if not api_key.strip():
        raise ValueError("Gemini API key is missing.")

    # Step 2: Initialize Gemini client
    client = genai.Client(api_key=api_key)

    MODEL = "gemini-3.1-flash-lite"

    # Step 3: Function to send prompts
    def send_prompt(prompt):
        response = client.models.generate_content(
            model=MODEL,
            contents=prompt,
            config={
                "temperature": 0.2,
                "max_output_tokens": 800
            }
        )
        return response.text or "No text response generated."

    # Step 4: Baseline prompt
    baseline_prompt = (
        "Explain recursion in programming. Describe its meaning, "
        "how it works, its importance, and give a simple example."
    )

    # Step 5: Enhanced prompt
    enhanced_prompt = (
        "You are a computer science professor teaching beginners. "
        "Explain recursion in simple English using a real-world analogy. "
        "Include a definition, base case, recursive case, a Python example, "
        "advantages, disadvantages, and a conclusion. Use clear headings "
        "and exactly five short paragraphs."
    )

    # Step 6: Generate baseline response
    print("=" * 60)
    print("EXPERIMENT 2: PROMPT ENGINEERING")
    print("=" * 60)

    print("\nBASELINE PROMPT:")
    print(baseline_prompt)

    baseline_response = send_prompt(baseline_prompt)

    print("\nBASELINE RESPONSE:")
    print(baseline_response)

    # Step 7: Generate enhanced response
    print("\nENHANCED PROMPT:")
    print(enhanced_prompt)

    enhanced_response = send_prompt(enhanced_prompt)

    print("\nENHANCED RESPONSE:")
    print(enhanced_response)

    # Step 8: Compare results
    print("\nCOMPARISON AND ANALYSIS")
    print("-" * 40)
    print("Baseline word count:", len(baseline_response.split()))
    print("Enhanced word count:", len(enhanced_response.split()))

    print("\nBaseline: General explanation with fewer instructions.")
    print("Enhanced: Specifies role, analogy, topics, and format.")

    print("\nRESULT:")
    print("Both prompts were tested using the same Gemini model.")
    print("Their responses were generated and compared successfully.")

except ValueError as e:
    print("Input Error:", e)

except Exception as e:
    print("API/Network Error:", e)